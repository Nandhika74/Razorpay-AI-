// Dynamically run the 4-stage recovery pipeline and simulate stochastic execution
function buildEvaluatedCase(spec: RawCaseSpec, split: 'design' | 'held_out'): RecoveryCase {
  const customer: CustomerProfile = {
    id: `cust_${spec.id.toLowerCase()}`,
    name: spec.name,
    email: spec.email,
    phone: spec.phone,
    planName: spec.planName,
    billingCycle: 'monthly',
    amountINR: spec.amountINR,
    currency: 'INR',
    cardNetwork: spec.network,
    cardLast4: '4242',
    cardExpiry: '12/28',
    mandateId: `mand_${spec.id.toLowerCase()}`,
    tenureMonths: spec.tenure,
    totalHistoricalPayments: spec.totalPayments,
    successfulHistoricalPayments: spec.successfulPayments,
    historicalSuccessRate: spec.successRate,
    lastSuccessDate: '2026-07-28T00:00:00.000Z',
    typicalSalaryDay: spec.typicalSalaryDay || 1,
    riskTier: spec.tenure >= 12 && spec.successRate >= 0.92 ? 'low_risk_vip' : spec.successRate >= 0.85 ? 'stable' : 'moderate',
  };

  const declineInfo: RazorpayDeclineInfo = {
    code: spec.errorCode,
    source: spec.source,
    step: spec.step,
    reason: spec.reason,
    description: `Razorpay Recurring Decline: ${spec.reason}`,
    httpStatusCode: 400,
    isTestMode: true,
  };

  // Stage 1: Diagnosis
  const diagnosis = runStage1Diagnosis(customer, declineInfo, 1);

  // Stage 2: 3-Zone Classification
  const classification = runStage2Classification(declineInfo, diagnosis);

  // Stage 3: Dual-Score Prioritization
  const trendScore = runStage3TrendScore(customer, diagnosis, classification, spec.daysRemaining);

  // Stage 4: Network Compliance Ceiling
  const compliance = runStage4ExecutionCompliance(customer, classification, 1);

  // Dynamic Stochastic Execution Resolution based on 4-Stage Predictive Likelihood
  // Roll deterministic PRNG based on case ID
  const roll = seededRandom(spec.id) * 100;

  let finalStatus: RecoveryCase['status'] = 'ACTIVE_DUNNING';
  let recoveryMethod: string | undefined = undefined;
  let hoursToRecovery: number | undefined = undefined;
  let attemptCount = 1;

  if (classification.zone === 'NEVER_RETRY') {
    // Hard Decline: Compliantly halted immediately with 0 retries
    finalStatus = 'EXCLUDED_HARD_DECLINE';
    attemptCount = 0;
    hoursToRecovery = 0;
  } else if (roll <= trendScore.recoveryLikelihoodPct) {
    // Successful Recovery
    finalStatus = 'RECOVERED';
    if (classification.zone === 'RETRY_SOON') {
      attemptCount = 1;
      hoursToRecovery = 0.5 + Math.round(seededRandom(`${spec.id}_hrs`) * 1.5 * 10) / 10;
      recoveryMethod = `Exponential Backoff Silent Retry (${Math.round(hoursToRecovery * 60)}m delay)`;
    } else if (classification.zone === 'RETRY_LATER') {
      attemptCount = 2;
      hoursToRecovery = 16 + Math.round(seededRandom(`${spec.id}_hrs`) * 20 * 10) / 10;
      recoveryMethod = `Payday-Aligned Smart Retry (${spec.typicalSalaryDay ? `${spec.typicalSalaryDay}th of Month` : 'Liquidity Window'})`;
    } else {
      attemptCount = 1;
      hoursToRecovery = 3 + Math.round(seededRandom(`${spec.id}_hrs`) * 5 * 10) / 10;
      recoveryMethod = 'Interactive 1-Click Mandate Recovery Link';
    }
  } else {
    // Unrecovered / In-Flight / Ceiling
    if (compliance.isCeilingReached) {
      finalStatus = 'HANDED_OFF_CEILING';
      attemptCount = compliance.maxAllowedAttempts;
    } else if (classification.zone === 'NEEDS_ACTION') {
      finalStatus = 'ACTION_REQUIRED_SENT';
      attemptCount = 1;
    } else {
      finalStatus = 'ACTIVE_DUNNING';
      attemptCount = 2;
    }
  }

  // Update compliance attempt count based on simulated execution
  compliance.attemptCount = attemptCount;
  compliance.attemptsRemaining = Math.max(0, compliance.maxAllowedAttempts - attemptCount);

  // Build authentic timestamped audit trail entries
  const auditTrail: AuditEntry[] = [
    {
      id: `aud_${spec.id}_1`,
      timestamp: '2026-08-28T00:00:12.000Z',
      stage: 1,
      stageName: 'Stage 1: Context-Adjusted Diagnosis',
      action: 'INGEST_WEBHOOK_AND_EVALUATE_BASELINE',
      resultStatus: 'DIAGNOSED',
      reason: diagnosis.explanation,
      actor: 'WEBHOOK_RECEIVER',
    },
    {
      id: `aud_${spec.id}_2`,
      timestamp: '2026-08-28T00:00:16.000Z',
      stage: 2,
      stageName: 'Stage 2: Zone Classification',
      action: `CLASSIFY_ZONE_${classification.zone}`,
      resultStatus: classification.zone,
      reason: classification.taxonomyNotes,
      complianceRule: classification.isHardDecline ? 'HARD_DECLINE_RULE_ZERO_RETRY' : undefined,
      actor: 'AI_AGENT',
    },
    {
      id: `aud_${spec.id}_3`,
      timestamp: '2026-08-28T00:00:17.000Z',
      stage: 3,
      stageName: 'Stage 3: Dual-Score Trend Assessment',
      action: 'CALCULATE_ORTHOGONAL_SCORES',
      resultStatus: `Likelihood ${trendScore.recoveryLikelihoodPct}% | Priority ${trendScore.recoveryPriorityScore}/100`,
      reason: trendScore.reasoning,
      actor: 'AI_AGENT',
    },
    {
      id: `aud_${spec.id}_4`,
      timestamp: '2026-08-28T00:00:18.000Z',
      stage: 4,
      stageName: 'Stage 4: Bounded Execution & Network Ceilings',
      action: compliance.isCeilingReached ? 'ENFORCE_CEILING_STOP' : `DISPATCH_${compliance.recommendedChannel}`,
      resultStatus: finalStatus,
      reason: compliance.complianceRuleApplied,
      complianceRule: `${compliance.network} Rolling-30D Cap: max ${compliance.maxAllowedAttempts} attempts`,
      actor: 'NETWORK_RULE_ENGINE',
    },
  ];

  if (finalStatus === 'RECOVERED') {
    auditTrail.push({
      id: `aud_${spec.id}_5`,
      timestamp: '2026-08-28T04:15:00.000Z',
      stage: 5,
      stageName: 'Ledger Audit Entry',
      action: 'REVENUE_CAPTURED_SUCCESSFULLY',
      resultStatus: 'RECOVERED',
      reason: `Recovered ₹${spec.amountINR.toLocaleString('en-IN')} via ${recoveryMethod || 'Automated Pipeline'}. Payment authorized on Razorpay.`,
      actor: 'WEBHOOK_RECEIVER',
    });
  }

  return {
    id: spec.id,
    batchSplit: split,
    customer,
    failureEvent: {
      paymentId: `pay_${spec.id.toLowerCase()}`,
      subscriptionId: `sub_${spec.id.toLowerCase()}`,
      timestamp: '2026-08-28T00:00:12.000Z',
      decline: declineInfo,
      attemptNumber: attemptCount,
    },
    currentStage: 4,
    diagnosis,
    classification,
    trendScore,
    compliance,
    status: finalStatus,
    recoveryMethod,
    recoveredAt: finalStatus === 'RECOVERED' ? '2026-08-28T04:15:00.000Z' : undefined,
    recoveredAmountINR: finalStatus === 'RECOVERED' ? spec.amountINR : undefined,
    hoursToRecovery,
    auditTrail,
  };
}

export function generateInitialCases(): RecoveryCase[] {
  const designCases = DESIGN_BATCH_SPECS.map(s => buildEvaluatedCase(s, 'design'));
  const heldOutCases = HELD_OUT_BATCH_SPECS.map(s => buildEvaluatedCase(s, 'held_out'));
  return [...designCases, ...heldOutCases];
}
